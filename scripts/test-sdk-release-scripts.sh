#!/usr/bin/env bash
#
# Tests the SDK release gates, scripts/sdk-version.sh, scripts/sdk-changelog.sh
# and scripts/sdk-release.sh, and the components they share,
# scripts/sdk-components.sh. The scripts decide whether a release can be
# tagged and what notes it carries, so every rule they enforce has a case
# here. .github/workflows/sdk-release-scripts.yaml runs this on pull requests.
#
#   scripts/test-sdk-release-scripts.sh
#
# Each case runs the real scripts against a throwaway git repository holding
# only a copy of them and the files they read: the version files and the
# release notes of every component, and the release tags and origin/main that
# the case needs. Nothing in this checkout is touched.
#
# scripts/sdk-release.sh asks npm and crates.io which versions exist. A fake
# `npm` and a fake `curl`, first on PATH, answer from files in a directory of
# the case instead, and record their calls, so no case reaches the network.
# Nothing beyond bash, git, node (which reads npm's answers) and the POSIX tools
# the scripts use is needed.
#
# The commands of the workflow steps that run scripts/sdk-release.sh, which are
# check-tree in the pull request check and the version step of each release
# workflow, are read from the workflows in this checkout, and run in such a
# repository as well. The conditions (`if:`) that decide whether the jobs and
# steps that publish run in the release workflows are read from them too, as
# text, and each has to be the one pinned here.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT

passed=0
failed=0

pass() {
    passed=$((passed + 1))
    echo "  ok    $1"
}

fail() {
    failed=$((failed + 1))
    echo "  FAIL  $1"
    [[ -z "${2:-}" ]] || printf '        %s\n' "${2//$'\n'/$'\n'        }"
}

# The files that hold the versions of the components, relative to a repository.
CATALOG=android/gradle/libs.versions.toml
CARGO_TOML=rust/fedimint-sdk/Cargo.toml
CARGO_LOCK=rust/fedimint-sdk/Cargo.lock
VERSION_SWIFT=ios/Sources/FedimintSdk/Version.swift
BINDINGS_MANIFEST=js/react-native/react-native-bindings/package.json
WRAPPER_MANIFEST=js/react-native/react-native/package.json

# Each of the next five prints a whole version file for the version $1, so that a case can
# compare a file with what it must hold after a write. Every other `version` in them is a decoy
# that no script may read or write.
catalog_toml() {
    printf '[versions]\nfedimintSdk = "%s"\n' "$1"
}

# With a second argument, a table with a decoy `version` comes before the package table: a
# workspace table for `first`, and a metadata table of the package for `metadata`.
cargo_toml() {
    case "${2:-}" in
        first) printf '[workspace.package]\nversion = "8.8.8"\n\n' ;;
        metadata) printf '[package.metadata.release]\nversion = "9.9.9"\n\n' ;;
    esac
    cat <<EOF
[package]
name = "fedimint-sdk"
version = "$1"
edition = "2024"

[package.metadata.docs]
version = "7.7.7"

[dependencies]
serde = "1"

[dependencies.other]
version = "9.9.9"
EOF
}

# The crate's entry has packages around it whose names contain its own, each with a version of
# its own. With a second argument, the entry is the last of the file, with no blank line after it.
cargo_lock() {
    cat <<EOF
# This file is automatically @generated by Cargo.
# It is not intended for manual editing.
version = 4

[[package]]
name = "aho-corasick"
version = "1.1.3"

[[package]]
name = "fedimint-sdk-macros"
version = "2.2.2"

[[package]]
name = "fedimint-sdk"
version = "$1"
dependencies = [
 "aho-corasick",
]
EOF
    if [[ -z "${2:-}" ]]; then
        cat <<'EOF'

[[package]]
name = "my-fedimint-sdk"
version = "3.3.3"

[[package]]
name = "zeroize"
version = "1.8.1"
EOF
    fi
}

version_swift() {
    cat <<EOF
// The only hand-written Swift in this SDK.
// public let fedimintSdkVersion = "9.9.9"

/// The version of the fedimint-sdk crate these bindings were generated from.
public let fedimintSdkVersion = "$1"
EOF
}

# $1 is the package's name and $2 its version. The nested object has a `version` that differs
# from the package's own in its indentation and in the number, and ends with a comma like it.
package_json() {
    cat <<EOF
{
  "name": "$1",
  "version": "$2",
  "private": true,
  "create-react-native-library": {
    "type": "module-new",
    "version": "0.41.2",
    "languages": "kotlin-swift"
  }
}
EOF
}

# The files that hold the version of the component $1, one per line. The first is the one that
# decides the component's version.
files_of() {
    case "$1" in
        rust) printf '%s\n' "$CARGO_TOML" "$CARGO_LOCK" "$VERSION_SWIFT" ;;
        android) printf '%s\n' "$CATALOG" ;;
        react-native) printf '%s\n' "$BINDINGS_MANIFEST" "$WRAPPER_MANIFEST" ;;
    esac
}

# Writes the version file $2 into the repository $1 at the version $3, without committing it.
put_file() {
    local dir="$1" path="$2" version="$3"
    mkdir -p "$(dirname "$dir/$path")"
    case "$path" in
        "$CATALOG") catalog_toml "$version" ;;
        "$CARGO_TOML") cargo_toml "$version" ;;
        "$CARGO_LOCK") cargo_lock "$version" ;;
        "$VERSION_SWIFT") version_swift "$version" ;;
        "$BINDINGS_MANIFEST") package_json @fedimint/react-native-bindings "$version" ;;
        "$WRAPPER_MANIFEST") package_json @fedimint/react-native "$version" ;;
    esac >"$dir/$path"
}

# Writes all the files that hold the version of the component $2 into the repository $1, at the
# version $3, without committing them.
put() {
    local dir="$1" component="$2" version="$3" path
    while IFS= read -r path; do
        put_file "$dir" "$path" "$version"
    done < <(files_of "$component")
}

# A fresh repository with every component at version $1, the given release notes (stdin) as
# the notes of every component, and a copy of the scripts, committed on main, with origin/main at
# that commit as a fetch would leave it. Prints its path.
repo() {
    local dir component
    dir="$(mktemp -d "$WORK/repo.XXXX")"
    mkdir -p "$dir/scripts" "$dir/android" "$dir/rust/fedimint-sdk" "$dir/js/react-native"
    cp "$ROOT/scripts/sdk-components.sh" "$ROOT/scripts/sdk-version.sh" \
        "$ROOT/scripts/sdk-changelog.sh" "$ROOT/scripts/sdk-release.sh" "$dir/scripts/"
    for component in rust android react-native; do
        put "$dir" "$component" "$1"
    done
    cat >"$dir/android/CHANGELOG.md"
    cp "$dir/android/CHANGELOG.md" "$dir/rust/fedimint-sdk/CHANGELOG.md"
    cp "$dir/android/CHANGELOG.md" "$dir/js/react-native/CHANGELOG.md"
    git -C "$dir" init -q -b main
    git -C "$dir" config user.name test
    git -C "$dir" config user.email test@example.invalid
    git -C "$dir" config commit.gpgSign false
    git -C "$dir" config tag.gpgSign false
    git -C "$dir" add -A
    git -C "$dir" commit -q -m base
    git -C "$dir" update-ref refs/remotes/origin/main HEAD
    echo "$dir"
}

# A fresh repository holding only a copy of the scripts and a base commit on main: no version
# files and no release notes. Prints its path.
bare_repo() {
    local dir
    dir="$(mktemp -d "$WORK/bare.XXXX")"
    mkdir -p "$dir/scripts"
    cp "$ROOT/scripts/sdk-components.sh" "$ROOT/scripts/sdk-version.sh" \
        "$ROOT/scripts/sdk-changelog.sh" "$dir/scripts/"
    git -C "$dir" init -q -b main
    git -C "$dir" config user.name test
    git -C "$dir" config user.email test@example.invalid
    git -C "$dir" add -A
    git -C "$dir" commit -q -m base
    echo "$dir"
}

# Commits a change to $2 (a path inside the repository) with subject $3.
change() {
    local dir="$1" path="$2" subject="$3"
    mkdir -p "$(dirname "$dir/$path")"
    echo "$subject" >>"$dir/$path"
    git -C "$dir" add -A
    git -C "$dir" commit -q -m "$subject"
}

# expect_ok <name> <expected stdout> -- <command...>
expect_ok() {
    local name="$1" want="$2" out
    shift 3
    if out="$("$@" 2>&1)"; then
        if [[ "$out" == "$want" ]]; then pass "$name"; else fail "$name" "expected: $want"$'\n'"got: $out"; fi
    else
        fail "$name" "exited non-zero: $out"
    fi
}

# expect_fail <name> <expected text in stderr> -- <command...>
expect_fail() {
    local name="$1" want="$2" out
    shift 3
    if out="$("$@" 2>&1)"; then
        fail "$name" "expected a failure, got: $out"
    elif [[ "$out" == *"$want"* ]]; then
        pass "$name"
    else
        fail "$name" "expected the error to mention: $want"$'\n'"got: $out"
    fi
}

# expect_usage <name> -- <command...>: fails with status 2 and prints the usage lines.
expect_usage() {
    local name="$1" out status=0
    shift 2
    out="$("$@" 2>&1)" || status=$?
    if [[ "$status" -eq 2 && "$out" == *usage* ]]; then
        pass "$name"
    else
        fail "$name" "expected exit status 2 and a usage message, got status $status: $out"
    fi
}

# Commits everything that changed in the repository $1, with subject $2.
commit_all() {
    git -C "$1" add -A
    git -C "$1" commit -q -m "$2"
}

# A repository like the ones repo prints, at version 0.1.0-beta.1 with finished notes, except
# that the file $1 holds $2 (with its backslash escapes expanded), committed. Prints its path.
broken_repo() {
    local dir
    dir="$(repo 0.1.0-beta.1 < <(finished_notes))"
    printf '%b' "$2" >"$dir/$1"
    commit_all "$dir" "break $1"
    echo "$dir"
}

# Puts the repository $1 back to its last commit and removes whatever was left behind.
reset_repo() {
    git -C "$1" checkout -q -- .
    git -C "$1" clean -fdq
}

# expect_changed <name> <repository> [<path>...]: since its last commit, exactly these files
# were modified in the repository, and nothing else was changed, added or left behind.
expect_changed() {
    local name="$1" dir="$2" want="" got
    shift 2
    if [[ $# -gt 0 ]]; then
        want="$(printf ' M %s\n' "$@" | LC_ALL=C sort)"
    fi
    got="$(git -C "$dir" status --porcelain --untracked-files=all | LC_ALL=C sort)"
    if [[ "$got" == "$want" ]]; then
        pass "$name"
    else
        fail "$name" "expected these changes: ${want:-none}"$'\n'"got: ${got:-none}"
    fi
}

# expect_file <name> <repository> <path> -- <generator...>: the file in the repository is, byte
# for byte, what the generator prints.
expect_file() {
    local name="$1" dir="$2" path="$3" got want
    shift 4
    got="$(
        cat "$dir/$path"
        echo x
    )"
    want="$(
        "$@"
        echo x
    )"
    if [[ "$got" == "$want" ]]; then
        pass "$name"
    else
        fail "$name" "$path is not what it should be:"$'\n'"$(diff <(printf '%s' "${want%x}") \
            <(printf '%s' "${got%x}") || true)"
    fi
}

# expect_output <name> <generator> -- <command...>: the command succeeds and prints, byte for
# byte, what the generator prints.
expect_output() {
    local name="$1" generator="$2" status=0
    shift 3
    "$generator" >"$WORK/output.expected"
    "$@" >"$WORK/output.actual" 2>"$WORK/output.errors" || status=$?
    if [[ "$status" -ne 0 ]]; then
        fail "$name" "exited with status $status: $(cat "$WORK/output.errors")"
    elif diff -u "$WORK/output.expected" "$WORK/output.actual" >"$WORK/output.diff"; then
        pass "$name"
    else
        fail "$name" "$(cat "$WORK/output.diff")"
    fi
}

# A checksum and the path of every file in the working tree of the repository $1 but its .git
# directory, by path, so that two calls print the same only if no file was added, removed or
# changed in between.
tree_sum() {
    (cd "$1" && find . -type f ! -path './.git/*' -exec cksum {} + | LC_ALL=C sort -k 3)
}

# expect_untouched <name> <repository> <expected text in stderr> -- <command...>: the command
# fails with that text in its error, and every file of the repository is, byte for byte, what it
# was before the command ran.
expect_untouched() {
    local name="$1" dir="$2" want="$3" before after out changes
    shift 4
    before="$(tree_sum "$dir")"
    if out="$("$@" 2>&1)"; then
        fail "$name" "expected a failure, got: $out"
        return
    fi
    after="$(tree_sum "$dir")"
    if [[ "$out" != *"$want"* ]]; then
        fail "$name" "expected the error to mention: $want"$'\n'"got: $out"
    elif [[ "$after" != "$before" ]]; then
        changes="$(diff <(echo "$before") <(echo "$after") || true)"
        fail "$name" "the repository changed:"$'\n'"$changes"
    else
        pass "$name"
    fi
}

