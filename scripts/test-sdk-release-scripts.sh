## 0.2.0

A paragraph that the file wraps
over three lines, with its
last line short.

Second paragraph,
also wrapped.

### Added

- First item that wraps
  onto a second line
  and a third.
- Second item.
  * Nested item that wraps
    over two lines.
  * Another nested item.
